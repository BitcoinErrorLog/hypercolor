export function catalogMetaById(id: string): VrtCatalogMeta {
  const entry = VRT_CATALOG_META.find(item => item.id === id);
  if (!entry) {
    throw new Error(`Unknown VRT catalog id: ${id}`);
  }
  return entry;
}

