function meta(
  id: string,
  journey: string,
  screen: string,
  state: string,
  mask: readonly VrtMaskRule[] = [],
): VrtCatalogMeta {
  return Object.freeze({
    id,
    journey,
    screen,
    platform: 'all' as VrtPlatform | 'all',
    viewport: 'all' as VrtViewport | 'all',
    theme: 'dark' as VrtTheme,
    state,
    mask: Object.freeze(mask) as readonly VrtMaskRule[],
  });
}

